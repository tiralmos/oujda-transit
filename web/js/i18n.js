export const LANGUAGES = [
  { code: 'fr', label: 'Français' },
  { code: 'en', label: 'English' },
  { code: 'ar', label: 'العربية' },
];

let current = 'fr';

export function initLanguage(fallback = 'fr') {
  const saved = load('lang', null);
  const browser = (navigator.language || '').slice(0, 2);
  current = [saved, browser, fallback, 'fr'].find((c) => c && STRINGS[c]);
  applyLanguage();
  return current;
}

export function setLanguage(code) {
  if (!STRINGS[code]) return;
  current = code;
  save('lang', code);
  applyLanguage();
}

export function getLanguage() {
  return current;
}

function applyLanguage() {
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
}

function lookup(key) {
  return STRINGS[current][key] ?? STRINGS.en[key] ?? key;
}

// Look up a string and fill {placeholders}, as plain text.
export function t(key, vars = {}) {
  return lookup(key).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
export const escapeHtml = (s) => String(s).replace(/[&<>"']/g, (c) => ESCAPES[c]);

// Wrap a value that is already HTML so th() inserts it unescaped.
export const raw = (html) => ({ __html: html });

// Like t(), but returns HTML: the string and every value are escaped,
// except values wrapped in raw().
export function th(key, vars = {}) {
  return escapeHtml(lookup(key)).replace(/\{(\w+)\}/g, (m, k) => {
    if (!(k in vars)) return m;
    const v = vars[k];
    return v && typeof v === 'object' && '__html' in v ? v.__html : escapeHtml(v);
  });
}

